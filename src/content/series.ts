/** 按系列 id 查 */
export function findSeries(id: string | undefined): CourseSeries | undefined {
  return id ? COURSE_SERIES.find((s) => s.id === id) : undefined;
}

/** 按学科取系列（默认 ai） */
export function mineSeriesByDomain(domainId: string): CourseSeries[] {
  return COURSE_SERIES.filter((s) => (s.domainId ?? 'ai') === domainId).sort((a, b) => a.order - b.order);
}

/** 按学科 + 分组归并（系列分组名由各学科自己定义） */
export function seriesByGroup(domainId = 'ai'): { group: string; items: CourseSeries[] }[] {
  const list = mineSeriesByDomain(domainId);
  const order =
    {
      ai: ['地基', '进阶', '应用'],
      mining: ['基础', '进阶', '应用'],
      'ai-auto': ['基础', '进阶', '应用'],
      quant: ['基础', '进阶', '实战'],
      ml: ['基础', '进阶', '前沿'],
      'data-engineering': ['核心工程'],
      'python-track': ['语言基石', '工程与 AI'],
    }[domainId] ?? [];
  const map = new Map<string, CourseSeries[]>();
  for (const s of list) {
    if (!map.has(s.group)) map.set(s.group, []);
    map.get(s.group)!.push(s);
  }
  const keys = order.length ? order.filter((g) => map.has(g)) : [...map.keys()];
  return keys.map((g) => ({ group: g, items: map.get(g)! }));
}
