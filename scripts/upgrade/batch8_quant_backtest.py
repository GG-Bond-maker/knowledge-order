import numpy as np
import pandas as pd

def risk_metrics(returns, rf_daily=0.0, periods=252):
    r = pd.Series(returns)
    ann_ret = r.mean() * periods
    ann_vol = r.std() * np.sqrt(periods)
    downside = r[r < rf_daily] - rf_daily
    dd_vol = np.sqrt((downside ** 2).sum() / (len(r) - 1)) * np.sqrt(periods)
    equity = r.cumsum()
    mdd = (equity - equity.cummax()).min()
    return {
        "年化收益": round(ann_ret, 4),
        "夏普": round((ann_ret - rf_daily * periods) / ann_vol, 2),
        "索提诺": round((ann_ret - rf_daily * periods) / dd_vol, 2),
        "Calmar": round(ann_ret / abs(mdd), 2) if mdd < 0 else None,
    }

rng = np.random.default_rng(1)
r = np.concatenate([rng.normal(0.001, 0.008, 200), rng.normal(0.0005, 0.02, 55)])
print(risk_metrics(r))
