def leverage(total_assets, noninterest, interest_debt, cash, ebitda):
    equity = total_assets - noninterest - interest_debt
    net_debt = interest_debt - cash
    return ((noninterest + interest_debt) / total_assets,
            net_debt / equity, net_debt / ebitda)

firms = {"高杠杆工业": leverage(1000, 250, 500, 120, 100),
         "无息占款龙头": leverage(600, 250, 0, 200, 80)}
