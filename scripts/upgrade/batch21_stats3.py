print(f"Cov = {cov}, Var(x) = {x.var():.1f}, Var(y) = {y.var():.1f}")
print(f"组合方差 Var(x+y) = {(x + y).var():.1f} "
      f"vs 独立假设 {x.var() + y.var():.1f}")

# 反向构造：把 y 倒序
