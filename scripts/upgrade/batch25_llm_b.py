ids  = [1,2,3, 6,7,8, 5, 1,4,3, 9,10,11, 5]     # 全文 token（示意）
roles = ["S","S","S", "U","U","U", "U", "S","S","S", "A","A","A", "A"]
labels = [t if r == "A" else -100 for t, r in zip(ids, roles)]
