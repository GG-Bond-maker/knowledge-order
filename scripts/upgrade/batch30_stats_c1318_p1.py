import math

def chi2_sf(x, df):
    # 卡方右尾概率 = 正则化不完全伽马 Q(df/2, x/2)
    a, z = df / 2, x / 2
    log_pref = -z + a * math.log(z) - math.lgamma(a)
    if z < a + 1:                      # 级数法：先算左尾再取补
        s = d = 1.0 / a; ap = a
        for _ in range(500):
            ap += 1; d *= z / ap; s += d
            if abs(d) < abs(s) * 1e-14: break
        return 1 - s * math.exp(log_pref)
    else:                              # 连分式法：直接算右尾
        tiny = 1e-300; b = z + 1 - a; c = 1 / tiny
        d = h = 1 / b
        for i in range(1, 500):
            an = -i * (i - a); b += 2
            d = an * d + b
            if abs(d) < tiny: d = tiny
            c = b + an / c
            if abs(c) < tiny: c = tiny
            d = 1 / d; de = d * c; h *= de
            if abs(de - 1) < 1e-14: break
        return math.exp(log_pref) * h

O = [10, 12, 8, 11, 9, 10]     # 60 次掷骰的观测频数
n = sum(O); E = [n / 6] * 6
chi2 = sum((o - e) ** 2 / e for o, e in zip(O, E))
print(f"chi2 = {chi2:.1f}, df = 5, p = {chi2_sf(chi2, 5):.4f}")

