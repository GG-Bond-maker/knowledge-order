from math import comb

# 小样本 A/B：新版按钮 10 人中 3 人转化，旧版 10 人中 8 人转化
a, b, c, d = 3, 7, 8, 2
n, r1, c1 = a + b + c + d, a + b, a + c

# 固定边际下 a 取每个可能值的超几何概率
probs = {k: comb(c1, k) * comb(n - c1, r1 - k) / comb(n, r1)
         for k in range(max(0, r1 - (n - c1)), min(r1, c1) + 1)}
p_obs = probs[a]
p_two = sum(p for p in probs.values() if p <= p_obs * (1 + 1e-9))
print(f"观测表概率 = {p_obs:.5f}")
for k in sorted(probs):
    print(f"a={k:2d}: P={probs[k]:.5f}"
          + ("  <- 观测或更极端" if probs[k] <= p_obs * (1 + 1e-9) else ""))
print(f"双侧 p 值 = {p_two:.4f}")
