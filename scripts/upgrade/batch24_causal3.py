import numpy as np
rng = np.random.default_rng(0)
T, n_per = 8, 300                     # 8 期面板
g = np.repeat([2, 4, 99], n_per)      # 组: 第2期/第4期处理/从未(99)

def gen(true_effect):
    unit = rng.normal(5, 1, len(g))                 # 个体固定效应
    time = np.linspace(0, 1, T)                     # 共同趋势
    eff = np.zeros((len(g), T))
