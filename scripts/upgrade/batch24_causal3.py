Y = gen(lambda dt: 1.0 + 0.5 * np.maximum(dt, 0))   # 效应 1 起步且随时间增长
print(f"真实效应(处理当期>=1 且递增); 交错面板已生成 {len(g)} 单元 x {T} 期")
print("下一节将演示: 对此数据跑 TWFE 会得到什么")
