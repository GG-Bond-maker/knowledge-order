def dupont5(rev, ebit, interest, tax, assets, equity):
    ebt = ebit - interest
    ni = ebt * (1 - tax)
    f = (ni / ebt, ebt / ebit, ebit / rev, rev / assets, assets / equity)
    return f, ni / equity

