import math, random
def Phi(x): return 0.5*(1+math.erf(x/math.sqrt(2)))
def ppf(p):  # 二分法求正态分位数
    lo, hi = -8.0, 8.0
    for _ in range(60):
        mid = (lo+hi)/2
        if Phi(mid) < p: lo = mid
        else: hi = mid
    return (lo+hi)/2
def qq_corr(x):
    n = len(x)
    th = [ppf((i-0.375)/(n+0.25)) for i in range(1, n+1)]
    xs = sorted(x)
    mx, mt = sum(xs)/n, sum(th)/n
    cov = sum((a-mx)*(b-mt) for a, b in zip(xs, th))
    vx = sum((a-mx)**2 for a in xs); vt = sum((b-mt)**2 for b in th)
    return cov/math.sqrt(vx*vt)
def skew(x):
    n=len(x); m=sum(x)/n
    s=math.sqrt(sum((a-m)**2 for a in x)/n)
    return sum((a-m)**3 for a in x)/n/s**3
