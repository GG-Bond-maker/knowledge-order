import numpy as np
rng = np.random.default_rng(7)
N, T = 3000, 60                       # 3000 股 × 60 个月

def rank_ic_eval(true_ic):
    ics = []
    for _ in range(T):
        f = rng.normal(0, 1, N)                       # 因子打分
        r = true_ic * f + np.sqrt(1 - true_ic**2) * rng.normal(0, 1, N)
        # RankIC：用秩的 Pearson 近似
