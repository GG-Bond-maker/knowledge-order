import numpy as np
rng = np.random.default_rng(122)
def anova_stats(means, sd, n, reps=5000):
    rej = 0; Fs = []
    for _ in range(reps):
        data = [rng.normal(m, sd, n) for m in means]
        alldata = np.concatenate(data); gm = alldata.mean()
        ssb = sum(len(g)*(g.mean()-gm)**2 for g in data)
        ssw = sum(((g-g.mean())**2).sum() for g in data)
        F = (ssb/(len(means)-1))/(ssw/(len(means)*n-len(means)))
        Fs.append(F)
