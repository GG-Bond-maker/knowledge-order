    nopat = ebit * (1 - tax)
    fcff = nopat + da - dnwc - capex
    ni = (ebit - interest) * (1 - tax)
    fcff_check = ni + interest * (1 - tax) + da - dnwc - capex
    fcfe = fcff - interest * (1 - tax) + net_borrow
    return nopat, fcff, fcff_check, fcfe

