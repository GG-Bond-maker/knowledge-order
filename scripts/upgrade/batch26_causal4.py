import numpy as np
rng = np.random.default_rng(0)
n = 30000
T = (rng.random(n) < 0.5).astype(float)
M = 2 + 1.5*T + rng.normal(0, 1, n)                  # 中介模型
Y = (0.20 + 0.04*T + 0.03*M + rng.normal(0, 0.3, n) > 0.5).astype(float)

# 拟合两模型(真实结构已知, 直接用真参数演示分解)
a1, b0, b1 = 1.5, 0.20, 0.04
c_M = 0.03
NDE, NIE = b1, c_M * a1
print(f"NDE = {NDE:.3f} (直接)  NIE = {NIE:.3f} (经活跃度)")
