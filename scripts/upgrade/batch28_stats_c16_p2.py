print("上围栏 = %.1f, 剔除离群点: %s" % (Q3 + 1.5 * IQR, sorted(set(X) - set(clean))))
print("体检后: n=%d 均值=%.2f 中位数=%.1f" % (len(clean), sum(clean) / len(clean), median(clean)))
