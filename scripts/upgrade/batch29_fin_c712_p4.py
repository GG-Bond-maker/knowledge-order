# 纯 Python OLS: 正规方程 + 高斯消元(标准库即可)
firms = [  # (1/A, (dREV-dREC)/A, PPE/A, TA/A) 健康同业
    (0.100, 0.150, 0.550, 0.095), (0.090, 0.120, 0.480, 0.080),
    (0.110, 0.180, 0.600, 0.120), (0.080, 0.100, 0.450, 0.068),
    (0.120, 0.200, 0.650, 0.138), (0.095, 0.140, 0.520, 0.098),
    (0.105, 0.160, 0.580, 0.112), (0.085, 0.110, 0.470, 0.075)]
X = [[1, f[0], f[1], f[2]] for f in firms]
y = [f[3] for f in firms]
k = 4
A = [[sum(X[r][i]*X[r][j] for r in range(len(X))) for j in range(k)] for i in range(k)]
b = [sum(X[r][i]*y[r] for r in range(len(X))) for i in range(k)]
for col in range(k):  # 高斯消元解 beta
    piv = max(range(col, k), key=lambda r: abs(A[r][col]))
    A[col], A[piv] = A[piv], A[col]; b[col], b[piv] = b[piv], b[col]
    for r in range(col + 1, k):
        f_ = A[r][col] / A[col][col]
        for cc in range(col, k): A[r][cc] -= f_ * A[col][cc]
        b[r] -= f_ * b[col]
beta = [0.0] * k
for r in range(k - 1, -1, -1):
    beta[r] = (b[r] - sum(A[r][cc]*beta[cc] for cc in range(r+1, k))) / A[r][r]
